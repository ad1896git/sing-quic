func TestTCPResponsePadding(t *testing.T) {
	// A fixed generator makes this independent of sync.Pool reuse.
	padding := strings.Repeat("aZ09", 64)
	original := generateTCPResponsePadding
	generateTCPResponsePadding = func() string { return padding }
	t.Cleanup(func() { generateTCPResponsePadding = original })

	poison := buf.NewSize(1024)
	if n, err := poison.Write(bytes.Repeat([]byte{0xAA}, 1024)); err != nil || n != 1024 {
		t.Fatalf("poison buffer: n=%d, err=%v", n, err)
	}
	poison.Release()

	buffer, err := WriteTCPResponse(true, "", nil)
	if err != nil {
		t.Fatal(err)
	}
	defer buffer.Release()
	r := bytes.NewReader(buffer.Bytes())
	status, err := r.ReadByte()
	if err != nil || status != 0 {
		t.Fatalf("status=%d, err=%v", status, err)
	}
	msgLen, err := quicvarint.Read(r)
	if err != nil || msgLen != 0 {
		t.Fatalf("message length=%d, err=%v", msgLen, err)
	}
	paddingLen, err := quicvarint.Read(r)
	if err != nil || paddingLen != uint64(len(padding)) {
		t.Fatalf("padding length=%d, err=%v", paddingLen, err)
	}
	got, err := io.ReadAll(r)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != padding {
		t.Fatal("padding does not equal the generated bytes")
	}
}

func TestTCPResponseMessageLength(t *testing.T) {
	for _, length := range []int{2048, 2049} {
		t.Run(fmt.Sprint(length), func(t *testing.T) {
			msg := strings.Repeat("m", length)
			buffer, err := WriteTCPResponse(false, msg, nil)
			if err != nil {
				t.Fatal(err)
			}
			defer buffer.Release()
			r := bytes.NewReader(buffer.Bytes())
			ok, got, err := ReadTCPResponse(r)
			if err != nil || ok || got != msg[:MaxMessageLength] {
				t.Fatalf("ok=%v, message length=%d, err=%v", ok, len(got), err)
			}
			if r.Len() != 0 {
				t.Fatalf("%d unexpected trailing bytes", r.Len())
			}
		})
	}
}

func TestTCPResponseRoundTrip(t *testing.T) {
	for _, tc := range []struct {
		name    string
		ok      bool
		message string
		payload []byte
	}{
		{"success", true, "connected", []byte("response payload")},
		{"failure", false, "connection refused", nil},
	} {
		t.Run(tc.name, func(t *testing.T) {
			buffer, err := WriteTCPResponse(tc.ok, tc.message, tc.payload)
			if err != nil {
				t.Fatal(err)
			}
			defer buffer.Release()
			r := bytes.NewReader(buffer.Bytes())
			ok, message, err := ReadTCPResponse(r)
			if err != nil || ok != tc.ok || message != tc.message {
				t.Fatalf("ok=%v, message=%q, err=%v", ok, message, err)
			}
			payload, err := io.ReadAll(r)
			if err != nil || !bytes.Equal(payload, tc.payload) {
				t.Fatalf("payload=%q, err=%v", payload, err)
			}
		})
	}
}

func TestParseUDPMessageTruncatedAddress(t *testing.T) {
	m := UDPMessage{SessionID: 1, PacketID: 2, FragCount: 1, Addr: "example.com:443"}
	packet := make([]byte, m.Size())
	if n := m.Serialize(packet); n != len(packet) {
		t.Fatalf("serialized %d bytes, want %d", n, len(packet))
	}
	for length := 0; length < len(packet); length++ {
		t.Run(fmt.Sprint(length), func(t *testing.T) {
			if _, err := ParseUDPMessage(packet[:length]); err == nil {
				t.Fatal("expected an error for a truncated address")
			}
		})
	}
	got, err := ParseUDPMessage(packet)
	if err != nil {
		t.Fatal(err)
	}
	if got.Addr != m.Addr || got.SessionID != m.SessionID || got.PacketID != m.PacketID || got.FragCount != m.FragCount {
		t.Fatalf("decoded message: %+v", got)
	}
}
